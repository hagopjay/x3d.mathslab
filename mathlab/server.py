"""Loopback educational app: bounded lesson data in, sampled models/X3D out.

This server never executes supplied Python, Manim code, XML or expressions.
The separate inherited Manim MCP CLI is a trusted-local code execution tool.
"""
from __future__ import annotations

import argparse
import hashlib
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import math
from pathlib import Path
import platform
import threading
from urllib.parse import unquote, urlsplit
import webbrowser

ROOT = Path(__file__).resolve().parents[1]
MAX_BODY = 32_768
MAX_RESPONSE = 4 * 1024 * 1024
VERSION = "0.3.0"
_WORKERS = threading.BoundedSemaphore(4)
_PRODUCERS = ('catalog.py', 'kernel.py', 'lessons_analysis.py', 'lessons_structures.py',
              'lessons_inference.py', 'lessons_science.py',
              'x3d.py', 'manim_bridge.py')
_PRODUCER_SHA = {name: hashlib.sha256((ROOT / 'mathlab' / name).read_bytes()).hexdigest()
                 for name in _PRODUCERS}
MIME = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
        '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
        '.json': 'application/json; charset=utf-8', '.x3d': 'model/x3d+xml',
        '.svg': 'image/svg+xml', '.png': 'image/png', '.woff2': 'font/woff2',
        '.woff': 'font/woff', '.ttf': 'font/ttf', '.otf': 'font/otf',
        '.wasm': 'application/wasm', '.mp4': 'video/mp4', '.txt': 'text/plain; charset=utf-8'}


def canonical(value) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
                      allow_nan=False).encode('utf-8')


def _pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError('Duplicate JSON key: ' + key)
        result[key] = value
    return result


def decode_request(raw: bytes) -> dict:
    if not raw or len(raw) > MAX_BODY:
        raise ValueError('Request must contain 1..32768 UTF-8 bytes.')
    try:
        value = json.loads(raw, object_pairs_hook=_pairs,
                           parse_constant=lambda token: (_ for _ in ()).throw(ValueError('Nonfinite JSON: ' + token)))
    except (UnicodeDecodeError, json.JSONDecodeError, RecursionError) as error:
        raise ValueError('Invalid UTF-8 JSON request.') from error
    if not isinstance(value, dict) or set(value) - {'lesson', 'params'}:
        raise ValueError('Expected only lesson and params.')
    if not isinstance(value.get('lesson'), str) or not 1 <= len(value['lesson']) <= 32:
        raise ValueError('A known lesson identifier is required.')
    params = value.get('params', {})
    if not isinstance(params, dict) or len(params) > 16:
        raise ValueError('params must be an object with at most sixteen numeric values.')
    for key, number in params.items():
        if not isinstance(key, str) or len(key) > 32 or isinstance(number, bool) or not isinstance(number, (int, float)):
            raise ValueError('Parameters must have short names and numeric values.')
        try:
            if not math.isfinite(number):
                raise ValueError('Parameters must be finite.')
        except OverflowError as error:
            raise ValueError('Parameter magnitude is too large.') from error
    return {'lesson': value['lesson'], 'params': params}


class ModelSourceChanged(RuntimeError):
    pass


def verify_producers() -> dict:
    files = {name: hashlib.sha256((ROOT / 'mathlab' / name).read_bytes()).hexdigest()
             for name in _PRODUCERS}
    if files != _PRODUCER_SHA:
        raise ModelSourceChanged('Model source changed while the server was running. Restart the local server.')
    return files


def identity(sample: dict, x3d: str) -> dict:
    files = verify_producers()
    return {'config_sha256': hashlib.sha256(canonical({'lesson': sample['lesson'], 'params': sample['params']})).hexdigest(),
            'sample_sha256': hashlib.sha256(canonical(sample)).hexdigest(),
            'x3d_sha256': hashlib.sha256(x3d.encode('utf-8')).hexdigest(),
            'source_sha256': files, 'python': platform.python_version(),
            'scope': 'Source configuration and generated bytes; not a full-state checkpoint or proof of mathematical claims.'}


def evaluate_request(request: dict) -> dict:
    verify_producers()
    from .kernel import evaluate
    from .x3d import to_x3d
    sample = evaluate(request['lesson'], request['params'])
    xml = to_x3d(sample)
    return {'sample': sample, 'x3d': xml, 'identity': identity(sample, xml)}


class Handler(BaseHTTPRequestHandler):
    server_version = 'MathLab/' + VERSION

    def setup(self):
        super().setup()
        self.connection.settimeout(8)

    def _local(self) -> bool:
        port = self.server.server_port
        hosts = {f'127.0.0.1:{port}', f'localhost:{port}'}
        host = self.headers.get('Host', '')
        origin = self.headers.get('Origin')
        return host in hosts and (not origin or origin in {f'http://{h}' for h in hosts})

    def _send(self, status: int, data: bytes, content_type: str):
        self.send_response(status)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(data)))
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('Cache-Control', 'no-store')
        self.send_header('Referrer-Policy', 'no-referrer')
        self.end_headers()
        try:
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _json(self, status: int, value: dict):
        data = canonical(value)
        if len(data) > MAX_RESPONSE:
            self._send(413, b'{"error":"Generated response exceeds the declared 4 MiB budget."}', MIME['.json'])
            return
        self._send(status, data, MIME['.json'])

    def do_GET(self):
        if not self._local():
            self._json(403, {'error': 'This app accepts its loopback origin only.'})
            return
        path = unquote(urlsplit(self.path).path)
        if path == '/api/health':
            self._json(200, {'name': 'x3d.mathlab', 'version': VERSION,
                             'python': platform.python_version(), 'execution': 'enumerated mathematical models only'})
            return
        if path == '/api/catalog':
            from .catalog import catalog
            self._json(200, {'lessons': catalog()})
            return
        if path.startswith('/docs/'):
            base, rel = ROOT / 'docs', path[len('/docs/'):]
        elif path.startswith('/examples/'):
            base, rel = ROOT / 'examples', path[len('/examples/'):]
        elif path.startswith('/web/'):
            # The authored guides share ../web/#lesson links with static Pages.
            # Retain that route alongside the loopback app's shorter root URL.
            base, rel = ROOT / 'web', path[len('/web/'):] or 'index.html'
        elif path == '/README.md':
            base, rel = ROOT, 'README.md'
        else:
            base, rel = ROOT / 'web', path.lstrip('/') or 'index.html'
        candidate = (base / rel).resolve()
        if not candidate.is_relative_to(base.resolve()) or not candidate.is_file():
            self._json(404, {'error': 'File not found.'})
            return
        self._send(200, candidate.read_bytes(), MIME.get(candidate.suffix.lower(), 'application/octet-stream'))

    def do_POST(self):
        if not self._local():
            self.close_connection = True
            self._json(403, {'error': 'This app accepts its loopback origin only.'})
            return
        if self.path not in ('/api/evaluate', '/api/manim'):
            self.close_connection = True
            self._json(404, {'error': 'Unknown endpoint.'})
            return
        if self.headers.get('Transfer-Encoding') or self.headers.get('Content-Type', '').split(';')[0].strip().lower() != 'application/json':
            self.close_connection = True
            self._json(415, {'error': 'Send bounded application/json with Content-Length.'})
            return
        try:
            size = int(self.headers.get('Content-Length', '-1'))
            if not 1 <= size <= MAX_BODY:
                self.close_connection = True
                self._json(413, {'error': 'Request size must be 1..32768 bytes.'})
                return
            request = decode_request(self.rfile.read(size))
            if not _WORKERS.acquire(blocking=False):
                self._json(429, {'error': 'Four model evaluations are already active. Try again shortly.'})
                return
            try:
                result = evaluate_request(request)
                if self.path == '/api/manim':
                    from .manim_bridge import generate_manim
                    result = {'source': generate_manim(result['sample']), 'identity': result['identity'],
                              'scope': 'Baked scene source only. This endpoint does not execute Python or render a video.'}
                self._json(200, result)
            finally:
                _WORKERS.release()
        except ModelSourceChanged as error:
            self._json(409, {'error': str(error)})
        except (ValueError, TypeError, KeyError, OverflowError, RecursionError) as error:
            self._json(400, {'error': str(error)[:300]})
        except Exception:
            self._json(500, {'error': 'Model generation failed. See local source and validation records.'})


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', type=int, default=8850)
    parser.add_argument('--open', action='store_true')
    args = parser.parse_args(argv)
    if not 1 <= args.port <= 65535:
        parser.error('Port must be 1..65535.')
    if not (ROOT / 'web/vendor/x_ite/dist/x_ite.min.js').is_file():
        parser.error('Bundled X_ITE runtime missing; restore the full distribution or run tools/vendor_xite.py.')
    server = ThreadingHTTPServer(('127.0.0.1', args.port), Handler)
    url = f'http://127.0.0.1:{args.port}/'
    print('x3d.mathlab:', url, flush=True)
    print('Local mathematical models. No API key or Manim installation is needed for the interactive lab.', flush=True)
    if args.open:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == '__main__':
    main()
